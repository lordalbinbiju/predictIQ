"""Business Intelligence & Retention Strategy Recommendation page."""

from __future__ import annotations

import streamlit as st

from src.business_insights import (
    compute_business_intelligence,
    plot_contract_risk_chart,
    plot_risk_segment_revenue,
)
from src.eda import plot_churn_by_tenure
from src.model_manager import ModelManager
from utils.helpers import format_currency, format_percent, render_kpi_card, render_page_header


def render() -> None:
    render_page_header(
        "Business Intelligence & Retention Analytics",
        "Quantify revenue exposure across churn risk tiers and review transparent rule-based retention guidance.",
    )

    df = st.session_state["dataset_df"]
    target_col = st.session_state["target_col"]
    model_mgr: ModelManager = st.session_state["model_manager"]
    active_bundle = model_mgr.load_model_bundle()

    high_risk_thresh = st.slider(
        "High-Risk Probability Threshold",
        min_value=0.45,
        max_value=0.85,
        value=0.65,
        step=0.05,
    )

    bi = compute_business_intelligence(
        df=df,
        target_col=target_col,
        bundle=active_bundle,
        high_risk_threshold=high_risk_thresh,
    )

    if bi["scored_with_model"]:
        st.caption(
            f"Risk segments computed using active model **{active_bundle['algorithm']}** "
            f"(`{active_bundle['model_version']}`)."
        )
    else:
        st.warning(
            "No trained model is active yet — displaying historical churn cohorts as a fallback. "
            "Train a model to segment customers by predicted churn probability."
        )

    k1, k2, k3, k4 = st.columns(4)
    with k1:
        render_kpi_card("Overall Churn Rate", format_percent(bi["overall_churn_rate"]))
    with k2:
        render_kpi_card(
            "High-Risk Customers",
            f"{bi['high_risk_count']:,}",
            f"{bi['high_risk_count'] / max(bi['total_customers'], 1) * 100:.1f}% of base",
        )
    with k3:
        render_kpi_card(
            "High-Risk Monthly Billing",
            format_currency(bi["high_risk_monthly_revenue"]),
            f"Annualized: {format_currency(bi['high_risk_annual_revenue'])}",
        )
    with k4:
        render_kpi_card(
            "Avg Monthly Charge (Churned)",
            format_currency(bi["avg_monthly_churned"]),
            f"vs. {format_currency(bi['avg_monthly_retained'])} retained",
        )

    st.markdown("<div style='height:0.75rem'></div>", unsafe_allow_html=True)

    c1, c2 = st.columns(2)
    with c1:
        if not bi["contract_summary"].empty:
            st.plotly_chart(
                plot_contract_risk_chart(bi["contract_summary"]),
                use_container_width=True,
            )
    with c2:
        st.plotly_chart(
            plot_risk_segment_revenue(bi["risk_segments"]),
            use_container_width=True,
        )

    if "tenure" in df.columns:
        st.plotly_chart(plot_churn_by_tenure(df, target_col), use_container_width=True)

    st.subheader("Customer Risk Segmentation Table")
    seg_display = bi["risk_segments"].copy()
    if "Observed Churn Rate" in seg_display.columns:
        seg_display["Observed Churn Rate"] = (seg_display["Observed Churn Rate"] * 100).round(2).astype(str) + "%"
    if "Avg Monthly Charges" in seg_display.columns:
        seg_display["Avg Monthly Charges"] = seg_display["Avg Monthly Charges"].round(2)
    if "Monthly Revenue" in seg_display.columns:
        seg_display["Monthly Revenue"] = seg_display["Monthly Revenue"].round(2)
    if "Avg Tenure (mo)" in seg_display.columns:
        seg_display["Avg Tenure (mo)"] = seg_display["Avg Tenure (mo)"].round(1)
    st.dataframe(seg_display, use_container_width=True, hide_index=True)

    st.subheader("Rule-Based Retention Recommendation Engine")
    st.info(
        "Methodological Note: These recommendations are generated by transparent, deterministic business rules "
        "applied to predicted risk segments and billing attributes. They represent prioritized hypotheses for "
        "retention outreach rather than experimentally validated causal outcomes."
    )

    for rec in bi["recommendations"]:
        st.markdown(
            f"""
            <div class="insight-item">
                <strong>{rec['segment']}</strong> — <em>{rec['volume']}</em><br/>
                <span style="font-size:0.83rem; color:#475569;">Rule: <code>{rec['rule']}</code></span><br/>
                {rec['recommendation']}
            </div>
            """,
            unsafe_allow_html=True,
        )
